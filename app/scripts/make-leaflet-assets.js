// Copies Leaflet (map library) into the app as text, so maps work without loading
// anything from a CDN. Run after upgrading leaflet: node scripts/make-leaflet-assets.js
const fs = require('fs');
const path = require('path');
const dist = path.join(__dirname, '..', 'node_modules', 'leaflet', 'dist');
const js = fs.readFileSync(path.join(dist, 'leaflet.js'), 'utf8');
const css = fs.readFileSync(path.join(dist, 'leaflet.css'), 'utf8');
const out = `// Generated by scripts/make-leaflet-assets.js from leaflet ${require('leaflet/package.json').version} (BSD-2-Clause). Do not edit.\nexport const LEAFLET_JS = ${JSON.stringify(js)};\nexport const LEAFLET_CSS = ${JSON.stringify(css)};\n`;
fs.writeFileSync(path.join(__dirname, '..', 'src', 'lib', 'leaflet-assets.ts'), out);
console.log('leaflet-assets.ts written', out.length, 'bytes');
